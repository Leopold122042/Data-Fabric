"""B owns implementations. A consumes these ports without writing execution data."""
from typing import Protocol

class EvidencePort(Protocol):
    def list(self) -> list[dict]: ...
    def get(self, oid: str) -> dict: ...

class ValidationPort(Protocol):
    def __call__(self, service: dict) -> dict: ...

class ControlPort(Protocol):
    def __call__(self, command: dict) -> dict: ...

class PlanPort(Protocol):
    def get(self, plan_id: str, version: int) -> dict: ...
