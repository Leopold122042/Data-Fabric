"""A's supported interfaces. Version identity is (id, version, environment)."""
from typing import Protocol

class CatalogPort(Protocol):
    def objects(self, **filters) -> list[dict]: ...
    def impact(self, oid: str) -> dict: ...

class SemanticPort(Protocol):
    def resolve(self, cid: str) -> dict: ...

class DefinitionStore(Protocol):
    def require(self, kind: str, oid: str, version: int | None = None) -> dict: ...
    def events(self, after: int = 0, limit: int = 200) -> list[dict]: ...
